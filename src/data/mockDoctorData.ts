/**
 * Rich Clinical Patient Data for Doctor's Portal
 */

export interface DoctorAppointment {
  readonly id: string;
  readonly doctorId: string; // 'dentist-jenkins' | 'dentist-thorne' | 'dentist-bennett'
  readonly doctorName: string;
  readonly patientName: string;
  readonly patientAge: number;
  readonly patientGender: 'Male' | 'Female' | 'Other';
  readonly patientPhone: string;
  readonly patientEmail: string;
  readonly patientType: 'New Patient' | 'Returning Patient';
  readonly timeSlot: string;
  readonly date: string;
  readonly operatory: string;
  readonly estimatedDuration: string;
  readonly status: 'Arrived / Checked In' | 'In Chair' | 'Next Up' | 'Completed';

  // "What's the problem" - Clinical intake & Chief complaint
  readonly chiefComplaint: string;
  readonly toothNumbers?: string;
  readonly painScale: number; // 0 - 10
  readonly symptoms: readonly string[];
  readonly medicalAlerts: readonly string[];
  readonly patientPreferences: {
    readonly nitrousOxide: boolean;
    readonly wheelchair: boolean;
    readonly quietOperatory: boolean;
    readonly boseHeadphones: boolean;
  };
  readonly insuranceCarrier: string;
  readonly memberId: string;
  readonly imagingAvailable: {
    readonly bitewingXrays: boolean;
    readonly iter03dScan: boolean;
    readonly intraoralPhotos: boolean;
  };
  readonly doctorNotes: string;
}

